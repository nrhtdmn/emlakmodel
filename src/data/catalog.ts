export function formatTRY(n: number) {
  return new Intl.NumberFormat('tr-TR', {
    style: 'currency',
    currency: 'TRY',
    maximumFractionDigits: 0,
  }).format(n)
}

export function getItem(id: string) {
  return CATALOG.find((c) => c.id === id)
}
